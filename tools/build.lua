-- Concatenates src/*.lua into dist/SCRIPTS/TOOLS/gaterush.lua (single file, no require).
-- Each module becomes `local name = (function() ... end)()`; its `local x = require("x")` lines are dropped.
local ORDER = { "config", "stats", "draw", "input", "track", "fx", "game", "screens" }
local OUT = "dist/SCRIPTS/TOOLS/gaterush.lua"

local function read(path)
  local f = assert(io.open(path, "rb"))
  local s = f:read("*a"):gsub("\r\n", "\n")
  f:close()
  return s
end

local function strip(src, name)
  local out = {}
  for line in (src .. "\n"):gmatch("(.-)\n") do
    local a, b = line:match('^local (%w+) = require%("(%w+)"%)%s*$')
    if a then
      assert(a == b, name .. ": require must be `local " .. b .. " = require(\"" .. b .. "\")`")
    else
      out[#out + 1] = line
    end
  end
  while out[#out] == "" do out[#out] = nil end
  return table.concat(out, "\n")
end

local parts = { "-- TNS|GateRush|TNE", "-- GateRush: twin-stick FPV tunnel game for EdgeTX B&W 128x64 radios.",
  "-- Generated by tools/build.lua from src/ - edit the sources, not this file.", "" }
for _, name in ipairs(ORDER) do
  parts[#parts + 1] = "local " .. name .. " = (function()"
  parts[#parts + 1] = strip(read("src/" .. name .. ".lua"), name)
  parts[#parts + 1] = "end)()"
  parts[#parts + 1] = ""
end
local main = strip(read("src/main.lua"), "main")
assert(main:match("return { init = init, run = run }$"), "main.lua must end with the script interface")
parts[#parts + 1] = main
local text = table.concat(parts, "\n") .. "\n"

assert(loadstring or load)(text, "=gaterush.lua")
local f = assert(io.open(OUT, "wb"))
f:write(text)
f:close()
print(string.format("built %s (%d bytes)", OUT, #text))
